import hashlib, os, subprocess, sys, tempfile, unittest
sys.path.insert(0, os.path.dirname(__file__))
import confidence as c

HERE = os.path.dirname(__file__)

class T(unittest.TestCase):
    def test_wilson_lower_bound(self):
        self.assertEqual(c.wilson_lower(0, 0), 0.0)
        self.assertAlmostEqual(c.wilson_lower(4, 5), 0.3755, places=3)
        self.assertAlmostEqual(c.wilson_lower(100, 100), 0.963, places=3)

    def test_counts_only_challenge_and_block_rows(self):
        rows = c.read_rows(os.path.join(HERE, 'fixtures', 'confidence_sample.csv'))
        counts = c.count(rows)
        self.assertEqual(counts, {'sqli.union-select': (4, 1), 'xss.script-tag': (1, 0)})

    def test_table_drops_constructs_below_five_rows(self):
        table = c.table({'sqli.union-select': (4, 1), 'xss.script-tag': (1, 0)}, min_rows=5)
        self.assertEqual(table, [('sqli.union-select', 37)])

    def test_rust_and_ts_outputs(self):
        rs = c.render_rust([('a.b', 9), ('c.d', 80)], 'src.csv', 'abc123', '2026-10-29')
        self.assertIn('("a.b", 9),', rs)
        self.assertIn('pub static TABLE', rs)
        ts = c.render_ts([('a.b', 9)], 'src.csv', 'abc123', '2026-10-29')
        self.assertIn("'a.b': 9,", ts)

    def test_cli_end_to_end_on_fixture(self):
        manifest_bytes = b"id\tside\nx\tdev\n"
        with tempfile.TemporaryDirectory() as d:
            man = os.path.join(d, 'manifest.tsv')
            rs_path = os.path.join(d, 'out.rs')
            ts_path = os.path.join(d, 'out.ts')
            with open(man, 'wb') as f:
                f.write(manifest_bytes)
            proc = subprocess.run(
                [sys.executable, '-I', '-X', 'utf8', os.path.join(HERE, 'confidence.py'),
                 os.path.join(HERE, 'fixtures', 'confidence_sample.csv'),
                 '--manifest', man, '--rust', rs_path, '--ts', ts_path, '--date', '2026-01-02'],
                capture_output=True, text=True, check=True)
            self.assertEqual(proc.stdout, '1 constructs\n')
            with open(rs_path, 'rb') as f:
                rs = f.read().decode('utf-8')
            with open(ts_path, 'rb') as f:
                ts = f.read().decode('utf-8')
        sha = hashlib.sha256(manifest_bytes).hexdigest()[:16]
        self.assertEqual(sha, '32adb7ec5adc3749')
        hdr = ('Generated by eval/confidence.py from confidence_sample.csv '
               '(manifest sha256 32adb7ec5adc3749, 2026-01-02). Do not edit.')
        self.assertEqual(rs, (
            '//! Measured confidence per deciding construct: floor(100 x Wilson 95 % lower bound\n'
            f'//! of dev precision). {hdr}\n'
            '\n'
            '/// Sorted by construct id.\n'
            'pub static TABLE: &[(&str, u8)] = &[\n'
            '    ("sqli.union-select", 37),\n'
            '];\n'
            '\n'
            '/// The measured confidence of a construct, if it decided enough dev rows.\n'
            'pub fn confidence(construct_id: &str) -> Option<u8> {\n'
            '    TABLE.binary_search_by(|(k, _)| (*k).cmp(construct_id)).ok().map(|i| TABLE[i].1)\n'
            '}\n'))
        self.assertEqual(ts, (
            f'// {hdr}\n'
            'export const CONFIDENCE: Record<string, number> = {\n'
            "  'sqli.union-select': 37,\n"
            '};\n'
            '\n'
            'export function confidenceOf(id: string | null): number | null {\n'
            '  return id !== null && id in CONFIDENCE ? CONFIDENCE[id] : null;\n'
            '}\n'))
        self.assertNotIn('\r', rs + ts)

if __name__ == '__main__':
    unittest.main()
