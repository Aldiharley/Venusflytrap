//! Benchmark harness: run regex baseline, tokenizer baseline, and the full
//! Venusflytrap engine over an identical corpus; emit a confusion matrix and
//! latency percentiles to a synthetic smoke report (not a result). Honesty requirement: the FP
//! count is always printed, never asserted to be zero.

use std::time::Instant;

use vft_core::{Config, Request, Shield, Verdict};

use crate::baselines::{RegexBaseline, TokenizerBaseline};
use crate::corpus::{self, Sample};

#[derive(Default, Clone)]
pub struct Confusion {
    pub tp: u64,
    pub fp: u64,
    pub tn: u64,
    pub fn_: u64,
}

impl Confusion {
    fn add(&mut self, predicted_attack: bool, actual_attack: bool) {
        match (predicted_attack, actual_attack) {
            (true, true) => self.tp += 1,
            (true, false) => self.fp += 1,
            (false, false) => self.tn += 1,
            (false, true) => self.fn_ += 1,
        }
    }
    pub fn precision(&self) -> f64 {
        let d = self.tp + self.fp;
        if d == 0 {
            0.0
        } else {
            self.tp as f64 / d as f64
        }
    }
    pub fn recall(&self) -> f64 {
        let d = self.tp + self.fn_;
        if d == 0 {
            0.0
        } else {
            self.tp as f64 / d as f64
        }
    }
    pub fn f1(&self) -> f64 {
        let (p, r) = (self.precision(), self.recall());
        if p + r == 0.0 {
            0.0
        } else {
            2.0 * p * r / (p + r)
        }
    }
    pub fn fp_rate(&self) -> f64 {
        let d = self.fp + self.tn;
        if d == 0 {
            0.0
        } else {
            self.fp as f64 / d as f64
        }
    }
}

struct EngineResult {
    name: String,
    overall: Confusion,
    obfuscated: Confusion,
    p50_us: u64,
    p95_us: u64,
    p99_us: u64,
}

fn pct(sorted: &[u64], p: f64) -> u64 {
    if sorted.is_empty() {
        return 0;
    }
    let idx = ((sorted.len() as f64 - 1.0) * p).round() as usize;
    sorted[idx]
}

fn request_for(value: &str) -> Request {
    let mut r = Request::get("/bench");
    r.query.push(("q".into(), value.to_string()));
    r
}

pub struct Report {
    pub markdown: String,
    pub full_recall_obfuscated: f64,
    pub full_fp_rate: f64,
    pub full_p95_us: u64,
}

pub fn run(seed: u64, n_each: usize) -> Report {
    let corpus = corpus::generate(seed, n_each);

    let regex = RegexBaseline::default();
    let tokenizer = TokenizerBaseline::default();
    let shield = Shield::new(Config::default());

    let regex_res = eval(&corpus, "Regex baseline", |s| regex.is_attack(&s.value));
    let tok_res = eval(&corpus, "Tokenizer baseline", |s| {
        tokenizer.is_attack(&s.value)
    });
    let full_res = eval(&corpus, "Venusflytrap (full)", |s| {
        let req = request_for(&s.value);
        matches!(
            shield.inspect(&req).verdict,
            Verdict::Block | Verdict::Challenge
        )
    });

    let markdown = render(&corpus, &[regex_res, tok_res, full_res.clone_light()], seed, n_each);
    Report {
        markdown,
        full_recall_obfuscated: full_res.obfuscated.recall(),
        full_fp_rate: full_res.overall.fp_rate(),
        full_p95_us: full_res.p95_us,
    }
}

impl EngineResult {
    fn clone_light(&self) -> EngineResult {
        EngineResult {
            name: self.name.clone(),
            overall: self.overall.clone(),
            obfuscated: self.obfuscated.clone(),
            p50_us: self.p50_us,
            p95_us: self.p95_us,
            p99_us: self.p99_us,
        }
    }
}

fn eval(corpus: &[Sample], name: &str, mut predict: impl FnMut(&Sample) -> bool) -> EngineResult {
    let mut overall = Confusion::default();
    let mut obfuscated = Confusion::default();
    let mut lat = Vec::with_capacity(corpus.len());
    for s in corpus {
        let t = Instant::now();
        let pred = predict(s);
        lat.push(t.elapsed().as_micros() as u64);
        overall.add(pred, s.attack);
        if s.kind.starts_with("obfuscated") {
            obfuscated.add(pred, s.attack);
        }
    }
    lat.sort_unstable();
    EngineResult {
        name: name.to_string(),
        overall,
        obfuscated,
        p50_us: pct(&lat, 0.50),
        p95_us: pct(&lat, 0.95),
        p99_us: pct(&lat, 0.99),
    }
}

fn render(corpus: &[Sample], results: &[EngineResult], seed: u64, n_each: usize) -> String {
    let mut m = String::new();
    m.push_str("# Synthetic smoke benchmark (not a result)\n\n");
    m.push_str(
        "This corpus is ~20 benign templates and the payloads the detectors were written \
         against. It checks that nothing is broken; it does not measure detection quality. \
         Real-corpus results: docs/BENCHMARK.md.\n\n",
    );
    m.push_str(&format!(
        "*Generated by `venusflytrap bench`. Deterministic corpus: seed={seed}, \
         {n_each} samples each of benign / attack / obfuscated ({} total).*\n\n",
        corpus.len()
    ));

    m.push_str("## Detection quality\n\n");
    m.push_str("| Engine | Recall (all) | Recall (obfuscated) | Precision | F1 | FP | FP rate |\n");
    m.push_str("|---|---|---|---|---|---|---|\n");
    for r in results {
        m.push_str(&format!(
            "| {} | {:.1}% | {:.1}% | {:.1}% | {:.3} | {} | {:.3}% |\n",
            r.name,
            r.overall.recall() * 100.0,
            r.obfuscated.recall() * 100.0,
            r.overall.precision() * 100.0,
            r.overall.f1(),
            r.overall.fp,
            r.overall.fp_rate() * 100.0,
        ));
    }

    m.push_str("\n## Confusion matrix (all samples)\n\n");
    m.push_str("| Engine | TP | FP | TN | FN |\n|---|---|---|---|---|\n");
    for r in results {
        m.push_str(&format!(
            "| {} | {} | {} | {} | {} |\n",
            r.name, r.overall.tp, r.overall.fp, r.overall.tn, r.overall.fn_
        ));
    }

    m.push_str("\n## Latency (per request, microseconds)\n\n");
    m.push_str("| Engine | p50 | p95 | p99 |\n|---|---|---|---|\n");
    for r in results {
        m.push_str(&format!(
            "| {} | {} µs | {} µs | {} µs |\n",
            r.name, r.p50_us, r.p95_us, r.p99_us
        ));
    }

    m.push_str("\n## Reading this\n\n");
    m.push_str(
        "- These rows only show that every engine runs end to end on a synthetic corpus built \
         from the payloads the detectors were written against. They are not evidence for or \
         against any claim in RESEARCH.md; measured results are in docs/BENCHMARK.md.\n",
    );
    m
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn confusion_math() {
        let mut c = Confusion::default();
        c.add(true, true);
        c.add(true, false);
        c.add(false, false);
        c.add(false, true);
        assert_eq!((c.tp, c.fp, c.tn, c.fn_), (1, 1, 1, 1));
        assert!((c.precision() - 0.5).abs() < 1e-9);
        assert!((c.recall() - 0.5).abs() < 1e-9);
    }

    #[test]
    fn full_engine_beats_regex_on_obfuscated() {
        let report = run(7, 50);
        // sanity: the report renders and full obfuscated recall is well above
        // zero (the regex baseline is near zero on double-encoded input).
        assert!(report.full_recall_obfuscated > 0.5, "{}", report.markdown);
        assert!(report.markdown.contains("Venusflytrap (full)"));
    }
}
